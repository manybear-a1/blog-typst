"""Validate a generated Anki CSV against its card-spec CSV and source Markdown.

Usage::

    python test_generate_cloze_csv.py CARD_SPECS.csv SOURCE.md OUTPUT.csv
"""

from argparse import ArgumentParser
import csv
from pathlib import Path
import re
import sys

from generate_cloze_csv import HEADER_COUNT, anki_headers, extract, read_card_specs


CLOZE_RE = re.compile(r"\{\{c\d+::.+?\}\}", re.DOTALL)


def read_generated_rows(output_path):
    """Read raw headers separately because #columns contains a comma."""
    lines = output_path.read_text(encoding="utf-8").splitlines(keepends=True)
    if len(lines) < HEADER_COUNT:
        raise AssertionError(f"{output_path} is missing Anki headers")
    header_text = [line.rstrip("\r\n") for line in lines[:HEADER_COUNT]]
    data_text = "".join(lines[HEADER_COUNT:])
    return header_text, list(csv.reader(data_text.splitlines()))


def validate(card_specs_path, source_path, output_path):
    """Raise an assertion with a useful message when generation is incorrect."""
    specs = read_card_specs(card_specs_path)
    source = source_path.read_text(encoding="utf-8")
    headers, rows = read_generated_rows(output_path)

    assert headers == anki_headers(source_path), "Anki headers do not match configuration"
    assert len(rows) == len(specs), "output row count does not match card-spec row count"
    assert all(len(row) == 2 for row in rows), "every output row must have two fields"
    assert all(CLOZE_RE.search(row[0]) for row in rows), "every prompt needs a cloze"
    assert all(row[1].lstrip().startswith("<") for row in rows), "extra must be HTML"
    all_output = "\n".join(field for row in rows for field in row)
    assert "&amp;lt;" not in all_output, "cloze HTML was double-escaped"
    assert "&amp;gt;" not in all_output, "cloze HTML was double-escaped"

    code_prompts = sum("```" in prompt for prompt, _, _ in specs)
    rendered_code_prompts = sum("<pre><code" in row[0] for row in rows)
    assert rendered_code_prompts == code_prompts, "code-block prompts were not converted to HTML"
    assert all("mdn-rendered-result" not in row[0] for row in rows), (
        "incomplete cloze prompts must not be rendered as MathML"
    )

    hard_cards = sum("{{c2::" in prompt or "```" in prompt for prompt, _, _ in specs)
    if len(specs) >= 4:
        assert hard_cards >= len(specs) // 2, (
            "too many easy cards: at least half the prompts must use multiple clozes "
            "or code reconstruction"
        )

    for prompt, start, end in specs:
        extract(source, start, end)
        assert "EmbedLiveSample" not in prompt
        assert "NextMenu" not in prompt

    assert "EmbedLiveSample" not in all_output
    assert "NextMenu" not in all_output
    assert "\\[" not in re.sub(r"\\&#x200D;\[", "", all_output)
    assert "\\]" not in re.sub(r"\\&#x200D;\]", "", all_output)


def main():
    parser = ArgumentParser(description="Validate an Anki cloze CSV generated by generate_cloze_csv.py.")
    parser.add_argument("card_specs", type=Path)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    validate(args.card_specs, args.source, args.output)
    print(f"validated: {args.output}")


if __name__ == "__main__":
    try:
        main()
    except (AssertionError, ValueError, FileNotFoundError) as error:
        print(f"validation failed: {error}", file=sys.stderr)
        raise SystemExit(1)
